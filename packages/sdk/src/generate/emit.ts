import openapiTS, { astToString } from 'openapi-typescript'
import type { Analysed } from './analyse.js'

export const GENERATE_COMMAND = 'pnpm -C packages/sdk generate'

/** What differs between the built-in files and a workspace's (DX604 D3): the header, the export names and where the helper types come from. */
export interface EmitProfile {
  header: string
  /** The table's export name and the map's type name. */
  operationsName: string
  mapName: string
  /** The module `OperationTable` is imported from, and the one the helper types (`ArgsOf`, ...) are. */
  tableFrom: string
  helpersFrom: string
}

const HEADER = `// GENERATED by \`${GENERATE_COMMAND}\` from the api and meta OpenAPI documents. Do not edit.
// Any change to an operation regenerates this file; the drift test (src/generate/drift.test.ts) fails until it does.
`

export const BUILT_IN_PROFILE: EmitProfile = {
  header: HEADER,
  operationsName: 'builtInOperations',
  mapName: 'BuiltInOperations',
  tableFrom: '../types.js',
  helpersFrom: '../typing.js',
}

const lit = (value: unknown, indent: number): string =>
  JSON.stringify(value, null, 2).replace(/\n/g, `\n${' '.repeat(indent)}`)
const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

/** The table: where each operation lives and where each argument goes (D2, D5, D12). */
export function emitOperations(ops: Analysed[], profile: EmitProfile = BUILT_IN_PROFILE): string {
  const rows = ops.map((o) => {
    const entry = {
      namespace: o.namespace,
      method: o.method,
      http: o.http,
      path: o.path,
      fields: o.fields,
      body: o.body,
      output: o.output,
      paginated: o.paginated,
      proposable: o.proposable,
      filters: o.filters,
    }
    return `  ${q(o.id)}: ${lit(entry, 2)},`
  })
  return `${profile.header}import type { OperationTable } from '${profile.tableFrom}'
import type { ${profile.mapName} } from './types.js'

export const ${profile.operationsName}: OperationTable<${profile.mapName}> = {
${rows.join('\n')}
}
`
}

async function documentTypes(document: unknown): Promise<string> {
  return astToString(await openapiTS(document as never)).trimEnd()
}

/** The map: openapi-typescript's translation of each document, and `BuiltInOperations` over it (D3, D12). */
export async function emitTypes(
  documents: { api: unknown; meta: unknown },
  ops: Analysed[],
  profile: EmitProfile = BUILT_IN_PROFILE,
): Promise<string> {
  const api = await documentTypes(documents.api)
  const meta = await documentTypes(documents.meta)
  const entries = ops.map((o) => {
    const ns = o.document === 'api' ? 'ApiDocument' : 'MetaDocument'
    const op = `${ns}.operations[${q(o.id)}]`
    const result =
      o.output === 'json' ? `ResultOf<${op}, ${o.status}>` : o.output === 'empty' ? 'undefined' : 'Response'
    const filterNames = Object.keys(o.filters)
    const args = filterNames.length
      ? `WithFilters<ArgsOf<${op}>, { ${filterNames
          .map((n) => `${q(n)}: [${q(o.filters[n].kind)}, ${o.filters[n].operators.map(q).join(' | ')}]`)
          .join('; ')} }>`
      : `ArgsOf<${op}>`
    return [
      `  ${q(o.id)}: {`,
      `    namespace: ${q(o.namespace)}`,
      `    method: ${q(o.method)}`,
      `    args: ${args}`,
      `    result: ${result}`,
      ...(o.paginated ? [`    item: ItemOf<${result}>`] : []),
      `    proposable: ${o.proposable}`,
      `    paginated: ${o.paginated}`,
      '  }',
    ].join('\n')
  })
  return `${profile.header}import type { ArgsOf, ItemOf, ResultOf, WithFilters } from '${profile.helpersFrom}'

/** openapi-typescript's translation of the api document. */
export namespace ApiDocument {
${api}
}

/** openapi-typescript's translation of the meta document. */
export namespace MetaDocument {
${meta}
}

/** The operation map: for each operation id, its client names, flat arguments and result (DX603 D12). */
export type ${profile.mapName} = {
${entries.join('\n')}
}
`
}
