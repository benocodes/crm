import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { generateWorkspace } from '@vibase/sdk/generate'
import { beforeAll, describe, expect, it } from 'vitest'
import {
  type Docs,
  instanceOf,
  projectWithTool,
  SCHEMA_NAME,
  SCHEMA_TEXT,
  SDK_DIR,
  TOOL_VERSION,
  workspaceDocuments,
} from './test/gen-rig.js'
import { KEY, rig, SERVER } from './test/harness.js'

// DX712 group 4 (DX694 D5 content, D6): the files the command writes, against the real openapi-typescript 7.13.0.
let docs: Docs
let project: string
let first: { operations: string; types: string }
let second: { operations: string; types: string }
let repo: { operations: string; types: string }
const read = (name: string) => readFileSync(join(project, 'src/vibase', name), 'utf8')
const files = () => ({ operations: read('operations.ts'), types: read('types.ts') })
const firstDifference = (a: string, b: string) => {
  const x = a.split('\n')
  const y = b.split('\n')
  for (let i = 0; i < Math.max(x.length, y.length); i++)
    if (x[i] !== y[i]) return `line ${i + 1}: ${JSON.stringify(x[i])} vs ${JSON.stringify(y[i])}`
  return 'no difference'
}
const body = (text: string) =>
  text
    .split('\n')
    .filter((_, i) => i >= 3)
    .join('\n')

beforeAll(async () => {
  docs = await workspaceDocuments()
  project = projectWithTool()
  const r = rig({ fetch: instanceOf(docs).fetch })
  await r.run(['login', '--api-key', '--server', SERVER, '--profile', 'zz-profile'], { stdin: KEY })
  const go = () => r.run(['gen', 'types', '--out', 'src/vibase', '--profile', 'zz-profile'], { cwd: project })
  const res = await go()
  if (res.code !== 0) throw new Error(`gen types failed: ${res.stderr}`)
  first = files()
  await go()
  second = files()
  repo = await generateWorkspace({ source: { schema: SCHEMA_TEXT, name: SCHEMA_NAME } })
  r.dispose()
}, 180_000)

describe('D6 the header', () => {
  it('is the three lines of the spec, with the origin, both versions and the loaded translator version', () => {
    const version = docs.api.info.version
    for (const text of [first.operations, first.types]) {
      expect(text.split('\n').slice(0, 3)).toEqual([
        "// GENERATED by `vibase gen types` from this instance's api and meta OpenAPI documents. Do not edit.",
        `// Source: ${SERVER}`,
        `// Documents: info.version ${version} (api), ${docs.meta.info.version} (meta). openapi-typescript ${TOOL_VERSION}. Regenerate after a schema file or release change.`,
      ])
      const header = text.split('\n').slice(0, 3).join('\n')
      expect(header).not.toMatch(/\d{4}-\d{2}-\d{2}/)
      expect(text).not.toContain('zz-profile')
    }
  })
})

describe('D5 the content', () => {
  it('equals the repo generator for the same documents, byte for byte below the header', () => {
    for (const k of ['operations', 'types'] as const)
      expect(firstDifference(body(first[k]), body(repo[k])), `${k}.ts`).toBe('no difference')
  })

  it('is byte-identical on a second run', () => {
    expect(second).toEqual(first)
  })

  it('typechecks with the custom namespace, a typed __c field and filter, and refuses a wrong enum value (typescript 5.9.3)', () => {
    const dir = mkdtempSync(join(tmpdir(), 'vibase-gen-tsc-'))
    mkdirSync(join(dir, 'node_modules/@vibase'), { recursive: true })
    symlinkSync(SDK_DIR, join(dir, 'node_modules/@vibase/sdk'))
    mkdirSync(join(dir, 'vibase'))
    writeFileSync(join(dir, 'vibase/operations.ts'), first.operations)
    writeFileSync(join(dir, 'vibase/types.ts'), first.types)
    writeFileSync(
      join(dir, 'check.ts'),
      `import { createClient } from '@vibase/sdk'
import { workspaceOperations } from './vibase/operations.js'
const vibase = createClient({ url: 'https://api.acme.example', auth: 't', operations: workspaceOperations })
export async function check() {
  await vibase.projects__c.list({ name: 'x' })
  await vibase.projects__c.list({ budget: { gte: 5000 } })
  await vibase.contacts.update({ id: 'c1', tier__c: 'gold' })
  // @ts-expect-error a value outside the enum
  await vibase.contacts.update({ id: 'c1', tier__c: 'platinum' })
  // @ts-expect-error a string on an integer filter
  await vibase.projects__c.list({ budget: { gte: 'lots' } })
}
`,
    )
    writeFileSync(
      join(dir, 'tsconfig.json'),
      JSON.stringify({
        compilerOptions: {
          target: 'ES2022',
          module: 'ESNext',
          moduleResolution: 'Bundler',
          lib: ['ES2022', 'DOM'],
          strict: true,
          skipLibCheck: true,
          noEmit: true,
          types: [],
        },
        files: ['check.ts'],
      }),
    )
    const tsc = join(SDK_DIR, 'node_modules/typescript/bin/tsc')
    let output = ''
    try {
      execFileSync(process.execPath, [tsc, '-p', dir], { encoding: 'utf8' })
    } catch (e) {
      output = String((e as { stdout?: string }).stdout)
    }
    expect(output.split('\n').slice(0, 5).join('\n')).toBe('')
  }, 120_000)
})
