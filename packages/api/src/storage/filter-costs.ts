// [[CORE199]] D10, D12 built by [[CORE201]]: the two checked-in lists of the registry filter contract. Plain data in package source, so the contract test
// checks them and discovery derives `indexed` from them at runtime (a column filter is indexed unless it is listed here).

/** A list x column filter whose `eq` D1 plan (default order) is not searched through an index that constrains that column, accepted with a reason. Exact: the contract fails on a missing, obsolete or unknown entry. */
export interface StatedFilterCost { readonly list: string; readonly filter: string; readonly reason: string }
/** A hand-written registry list outside the filter rollout, with the reason. */
export interface FilterExemption { readonly list: string; readonly reason: string }

const COLUMN = 'no (organization_id, column, id) index (D12): eq reads the organisation\'s live rows, hundreds to low thousands outside mail'
const MAIL = 'no index constrains this column (D12): eq reads the organisation\'s live rows of a mail table, the largest tables; a measured slow filter gets an (organization_id, column, id) index at the next migration (D12)'
// Reasons that name an existing index are checked against the D1 migrations (every index and UNIQUE constraint of the table, partial ones included).
/** An index can be searched by this column alone (organization_id is always bound), but the plan at the default order searches the (organization_id, id) index instead, to avoid a sort. */
const kept = (index: string, shape: string) =>
  `${index} ${shape} can be searched by this column alone, but the plan at the default order searches the (organization_id, id) index instead, to avoid a sort, so eq reads the organisation's live rows; the D12 remedy is an (organization_id, column, id) index`
/** The only index with this column has columns before it: eq on this column alone cannot search it. */
const behind = (index: string, shape: string, need: string, remedy: string) =>
  `${index} ${shape} has this column after ${need}, so eq on this column alone cannot search it and reads the organisation's live rows; add ${need} to the filter, or (D12) ${remedy}`
/** The only indexes with this column are partial, and a bare eq does not imply their WHERE clause. */
const partial = (index: string, shape: string, where: string) =>
  `only the partial index ${index} ${shape} WHERE ${where} has this column, and a bare eq does not imply that condition, so eq reads the organisation's live rows; the D12 remedy is an (organization_id, column, id) index`
const SMALL = 'the table holds a handful of rows per workspace (D12) and no index constrains this column: eq reads them all'
// [[CORE188]] D5: action_executions is read through `operation IN (the readable operations)`, so the planner searches the (organization_id, operation) index once
// per operation, and every other column is checked on those rows.
const EXECUTION = 'the visibility predicate is operation IN (the readable operations): the planner searches the (organization_id, operation) index per operation and this column is checked on those rows'

